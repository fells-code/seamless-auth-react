import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

// The screens' stylesheet is shared by the bindings and lives at the repository
// root. svelte-package does not bundle, so the Svelte binding carries it as a
// generated module the layout injects. Generated, not committed, so it cannot
// drift from the shared file.

const root = path.resolve(process.cwd(), '..', '..');
const css = await readFile(
  path.join(root, 'resources', 'styles', 'seamless-auth.css'),
  'utf8'
);

await writeFile(
  path.join(process.cwd(), 'src', 'styles.generated.ts'),
  `// Generated by scripts/generate-svelte-styles.mjs from resources/styles/seamless-auth.css.\nexport default ${JSON.stringify(css)};\n`
);
